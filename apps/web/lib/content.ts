type Option = [
  string,
  number,
  number,
  number,
  number,
  number,
  string,
  Choice["tag"],
];
function scenario(
  place: PlaceId,
  key: string,
  object: string,
  stage: Scenario["stage"],
  title: string,
  description: string,
  options: Option[],
): Scenario {
  return {
    id: key,
    place,
    object,
    stage,
    title,
    description,
    choices: options.map((o, i) => ({
      id: `${key}-${i}`,
      title: o[0],
      cost: o[1],
      minutes: o[2],
      energy: o[3],
      inspiration: o[4],
      connection: o[5],
      outcome: o[6],
      tag: o[7],
    })),
  };
}
